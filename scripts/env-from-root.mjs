#!/usr/bin/env node
/**
 * Writes this checkout's `.env` from a Firebase web config `.env` that uses plain names (API_KEY, AUTH_DOMAIN,
 * PROJECT_ID, STORAGE_BUCKET, MESSAGING_SENDER_ID, APP_ID, MEASUREMENT_ID), mapping them to the app's
 * `EXPO_PUBLIC_FIREBASE_*` names.
 *
 *   node scripts/env-from-root.mjs [--source <path to .env>] [--emulator]
 *
 * Default source: the `.env` at the root of the main repository (works from a git worktree too).
 * Safety: never prints values (only which names were found), refuses to write unless `.env` is git-ignored, and
 * never modifies the source file. `--emulator` sets EXPO_PUBLIC_USE_FIREBASE_EMULATOR=true for local development.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

const MAP = {
  API_KEY: 'EXPO_PUBLIC_FIREBASE_API_KEY',
  AUTH_DOMAIN: 'EXPO_PUBLIC_FIREBASE_AUTH_DOMAIN',
  PROJECT_ID: 'EXPO_PUBLIC_FIREBASE_PROJECT_ID',
  STORAGE_BUCKET: 'EXPO_PUBLIC_FIREBASE_STORAGE_BUCKET',
  MESSAGING_SENDER_ID: 'EXPO_PUBLIC_FIREBASE_MESSAGING_SENDER_ID',
  APP_ID: 'EXPO_PUBLIC_FIREBASE_APP_ID',
  MEASUREMENT_ID: 'EXPO_PUBLIC_FIREBASE_MEASUREMENT_ID',
};
const REQUIRED = ['API_KEY', 'AUTH_DOMAIN', 'PROJECT_ID', 'APP_ID'];

const arg = (name) => {
  const i = process.argv.indexOf(`--${name}`);
  return i >= 0 ? process.argv[i + 1] : undefined;
};

function mainRepoRoot() {
  const common = execFileSync('git', ['rev-parse', '--path-format=absolute', '--git-common-dir'], { encoding: 'utf8' });
  return dirname(common.trim());
}

function parseEnv(text) {
  const out = {};
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const m = /^(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)$/.exec(line);
    if (!m) continue;
    let value = m[2].trim();
    if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }
    out[m[1]] = value;
  }
  return out;
}

const target = resolve('.env');
const source = resolve(arg('source') ?? join(mainRepoRoot(), '.env'));
if (source === target) throw new Error('Source and target are the same file; refusing to overwrite it.');
if (!existsSync(source)) throw new Error(`No source .env found at ${source}`);

try {
  execFileSync('git', ['check-ignore', '-q', '.env']);
} catch {
  throw new Error('.env is not git-ignored in this checkout; refusing to write it.');
}

const input = parseEnv(readFileSync(source, 'utf8'));
const found = Object.keys(MAP).filter((k) => input[k]);
const missing = REQUIRED.filter((k) => !input[k]);
if (missing.length) throw new Error(`Source .env is missing required names: ${missing.join(', ')}`);

const lines = [
  '# Generated by scripts/env-from-root.mjs from the main repository .env (values not shown anywhere). Git-ignored.',
  ...found.map((k) => `${MAP[k]}=${input[k]}`),
  `EXPO_PUBLIC_USE_FIREBASE_EMULATOR=${process.argv.includes('--emulator') ? 'true' : 'false'}`,
  'EXPO_PUBLIC_FIREBASE_EMULATOR_HOST=127.0.0.1',
  '',
];
writeFileSync(target, lines.join('\n'), { mode: 0o600 });
console.log(`Wrote .env with: ${found.map((k) => MAP[k]).join(', ')}, EXPO_PUBLIC_USE_FIREBASE_EMULATOR`);
