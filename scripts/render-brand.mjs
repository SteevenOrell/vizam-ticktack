#!/usr/bin/env node
/**
 * Generates TickTack brand assets from code (no stock photos, no AI images):
 *   - src/ui/brand/wordmarkData.ts   wordmark glyph paths (Space Grotesk 500, OFL) + orange hand geometry
 *   - assets/splash/splash-{day,night}.webp   "ember flow" backgrounds for the in-app splash (1290 x 2796)
 *   - assets/splash-wordmark.png     native splash image (wordmark inside the Android 12 icon circle)
 *   - assets/icon.png, android-icon-foreground.png, android-icon-monochrome.png, favicon.png
 * Run: npm run render:brand
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { Resvg } from '@resvg/resvg-js';
import opentype from 'opentype.js';
import sharp from 'sharp';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = (p) => join(root, p);

const ORANGE = '#FF7A24';
const CHARCOAL = '#17191B';
const WHITE = '#FFFFFF';

// ---------------------------------------------------------------------------------------------------------------
// 1. Wordmark: "ticktack" lowercase, the i drawn dotless with a short orange bar tilted like a watch hand as its dot.
// ---------------------------------------------------------------------------------------------------------------
const fontFile = out('node_modules/@expo-google-fonts/space-grotesk/500Medium/SpaceGrotesk_500Medium.ttf');
const buf = readFileSync(fontFile);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));

const SIZE = 100; // design units: font size 100
const TRACKING = -0.02 * SIZE; // -2% (display style)
const text = 'tıcktack';
const dotless = font.charToGlyph('ı');
if (!dotless || dotless.index === 0) throw new Error('Space Grotesk has no dotless i glyph');

let x = 0;
const parts = [];
let iBox = null;
const glyphs = font.stringToGlyphs(text);
glyphs.forEach((g, i) => {
  const path = g.getPath(x, 0, SIZE);
  parts.push(path.toPathData(2));
  if (i === 1) iBox = path.getBoundingBox();
  const next = glyphs[i + 1];
  const kern = next ? font.getKerningValue(g, next) : 0;
  x += ((g.advanceWidth + kern) / font.unitsPerEm) * SIZE + (next ? TRACKING : 0);
});
const lettersPath = parts.join(' ');
const full = font.getPath(text, 0, 0, SIZE, { kerning: true, letterSpacing: -0.02 }).getBoundingBox();
const xHeight = (font.tables.os2.sxHeight / font.unitsPerEm) * SIZE;

// Orange hand: centred over the dotless i, tilted ~35° like a clock hand pointing to one o'clock.
const stem = { cx: (iBox.x1 + iBox.x2) / 2, w: iBox.x2 - iBox.x1 };
const handWidth = stem.w * 1.05;
const handLen = SIZE * 0.24;
const angle = (35 * Math.PI) / 180;
const baseY = -xHeight - SIZE * 0.1; // bottom of the hand, just above the stem
const hand = {
  x1: round(stem.cx - Math.sin(angle) * handWidth * 0.2),
  y1: round(baseY),
  x2: round(stem.cx + Math.sin(angle) * handLen),
  y2: round(baseY - Math.cos(angle) * handLen),
  width: round(handWidth),
};

function round(n) {
  return Math.round(n * 100) / 100;
}

const pad = SIZE * 0.04;
const minX = Math.min(full.x1, hand.x1 - hand.width) - pad;
const minY = Math.min(full.y1, hand.y2 - hand.width) - pad;
const maxX = Math.max(full.x2, hand.x2 + hand.width) + pad;
const maxY = full.y2 + pad;
const viewBox = [round(minX), round(minY), round(maxX - minX), round(maxY - minY)];

mkdirSync(out('src/ui/brand'), { recursive: true });
writeFileSync(
  out('src/ui/brand/wordmarkData.ts'),
  `// Generated by scripts/render-brand.mjs from Space Grotesk Medium (SIL Open Font License). Do not edit by hand.
export const wordmarkViewBox = [${viewBox.join(', ')}] as const;
export const wordmarkLetters =
  '${lettersPath}';
export const wordmarkHand = ${JSON.stringify(hand)} as const;
`,
);

function wordmarkSvg({ width, color = WHITE, handColor = ORANGE, x0 = 0, y0 = 0 }) {
  const scale = width / viewBox[2];
  return `<g transform="translate(${x0} ${y0}) scale(${scale}) translate(${-viewBox[0]} ${-viewBox[1]})">
    <path d="${lettersPath}" fill="${color}"/>
    <line x1="${hand.x1}" y1="${hand.y1}" x2="${hand.x2}" y2="${hand.y2}" stroke="${handColor}" stroke-width="${hand.width}" stroke-linecap="round"/>
  </g>`;
}
const wordmarkAspect = viewBox[3] / viewBox[2];

// ---------------------------------------------------------------------------------------------------------------
// 2. Splashes (DESIGN.md section 3): day white -> orange (charcoal wordmark), night blue ember flow (white wordmark).
// ---------------------------------------------------------------------------------------------------------------
const W = 1290;
const H = 2796;
const stops = {
  night: ['#0B0B0C', '#17191B', '#1E3A8A', '#2B4FB0', '#5B8FD6', '#9DBEEA', '#E6F0FF'],
};

// Day splash (phase 3 feedback): light white -> orange gradient, orange at the bottom, soft warm blooms and the same
// fine grain. The centre stays near #FFF1E6 so the charcoal wordmark reads at full contrast.
const DAY = ['#FFFFFF', '#FFF1E6', '#FFC9A1', '#FF7A24'];
function splashDaySvg() {
  const [white, cream, peach, orange] = DAY;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">
  <defs>
    <linearGradient id="base" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="${white}"/>
      <stop offset="0.42" stop-color="${cream}"/>
      <stop offset="0.74" stop-color="${peach}"/>
      <stop offset="1" stop-color="${orange}"/>
    </linearGradient>
    <filter id="blur" filterUnits="userSpaceOnUse" x="-400" y="-400" width="${W + 800}" height="${H + 800}"><feGaussianBlur stdDeviation="170"/></filter>
    <filter id="grain" x="0" y="0" width="100%" height="100%">
      <feTurbulence type="fractalNoise" baseFrequency="0.85" numOctaves="2" seed="7" result="noise"/>
      <feColorMatrix type="saturate" values="0"/>
    </filter>
  </defs>
  <rect width="${W}" height="${H}" fill="url(#base)"/>
  <g filter="url(#blur)">
    <ellipse cx="300" cy="300" rx="700" ry="300" fill="${white}" opacity="0.9"/>
    <ellipse cx="1180" cy="2050" rx="700" ry="260" transform="rotate(-18 1180 2050)" fill="${peach}" opacity="0.8"/>
    <ellipse cx="200" cy="2600" rx="900" ry="300" transform="rotate(-10 200 2600)" fill="${orange}" opacity="0.55"/>
    <ellipse cx="1100" cy="2800" rx="900" ry="280" fill="${orange}" opacity="0.8"/>
  </g>
  <rect width="${W}" height="${H}" filter="url(#grain)" opacity="0.05"/>
</svg>`;
}

function splashSvg(period) {
  if (period === 'day') return splashDaySvg();
  const [black, charcoal, deep, strong, bright, warm, cream] = stops[period];
  // Blobs: a deep streak entering from the top right, bending down-left through the centre, then the bright bands
  // sweep back to the right and end in a cream glow at the bottom right.
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">
  <defs>
    <linearGradient id="base" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="${black}"/>
      <stop offset="0.38" stop-color="${charcoal}"/>
      <stop offset="0.62" stop-color="${deep}"/>
      <stop offset="1" stop-color="${strong}"/>
    </linearGradient>
    <filter id="blur" filterUnits="userSpaceOnUse" x="-400" y="-400" width="${W + 800}" height="${H + 800}"><feGaussianBlur stdDeviation="150"/></filter>
    <filter id="soft" filterUnits="userSpaceOnUse" x="-400" y="-400" width="${W + 800}" height="${H + 800}"><feGaussianBlur stdDeviation="90"/></filter>
    <filter id="grain" x="0" y="0" width="100%" height="100%">
      <feTurbulence type="fractalNoise" baseFrequency="0.85" numOctaves="2" seed="7" result="noise"/>
      <feColorMatrix type="saturate" values="0"/>
    </filter>
  </defs>
  <rect width="${W}" height="${H}" fill="url(#base)"/>
  <g filter="url(#blur)">
    <ellipse cx="1150" cy="620" rx="520" ry="150" transform="rotate(-58 1150 620)" fill="${deep}" opacity="0.75"/>
    <ellipse cx="640" cy="1400" rx="1250" ry="430" transform="rotate(-30 640 1400)" fill="${deep}"/>
    <ellipse cx="300" cy="1900" rx="700" ry="300" transform="rotate(-20 300 1900)" fill="${deep}"/>
    <ellipse cx="860" cy="1830" rx="1000" ry="250" transform="rotate(-24 860 1830)" fill="${strong}"/>
    <ellipse cx="980" cy="2080" rx="900" ry="230" transform="rotate(-16 980 2080)" fill="${bright}"/>
    <ellipse cx="1060" cy="2400" rx="820" ry="260" transform="rotate(-8 1060 2400)" fill="${warm}"/>
  </g>
  <g filter="url(#soft)">
    <ellipse cx="760" cy="2780" rx="1050" ry="300" fill="${cream}"/>
    <ellipse cx="1180" cy="2650" rx="520" ry="330" fill="${cream}"/>
  </g>
  <rect width="${W}" height="${H}" filter="url(#grain)" opacity="0.07"/>
</svg>`;
}

mkdirSync(out('assets/splash'), { recursive: true });
for (const period of ['day', 'night']) {
  if (process.env.DUMP_SVG) writeFileSync(join(process.env.DUMP_SVG, `splash-${period}.svg`), splashSvg(period));
  const png = new Resvg(splashSvg(period)).render().asPng();
  await sharp(png)
    .webp({ quality: 80, effort: 6 })
    .toFile(out(`assets/splash/splash-${period}.webp`));
  // Preview with the wordmark composited, for reviewing the centre contrast (not shipped).
  if (process.argv.includes('--preview')) {
    const ww = W * 0.75;
    const wh = ww * wordmarkAspect;
    const svg = splashSvg(period).replace(
      '</svg>',
      `${wordmarkSvg({ width: ww, x0: (W - ww) / 2, y0: H / 2 - wh / 2, color: period === 'day' ? CHARCOAL : WHITE })}</svg>`,
    );
    await sharp(new Resvg(svg).render().asPng())
      .resize({ width: 645 })
      .webp({ quality: 80 })
      .toFile(out(`docs/screenshots/phase-3-feedback/brand-preview-${period}.webp`));
  }
}

// ---------------------------------------------------------------------------------------------------------------
// 3. Native splash image: square canvas; the wordmark stays inside Android 12's 2/3 icon circle.
// ---------------------------------------------------------------------------------------------------------------
{
  const S = 1152;
  const ww = S * 0.62;
  const wh = ww * wordmarkAspect;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${S}" height="${S}">${wordmarkSvg({ width: ww, x0: (S - ww) / 2, y0: (S - wh) / 2, color: CHARCOAL })}</svg>`;
  writeFileSync(out('assets/splash-wordmark.png'), new Resvg(svg).render().asPng());
}

// ---------------------------------------------------------------------------------------------------------------
// 4. App icon: orange watch hand plus a check stroke on charcoal. No clock clip-art.
// ---------------------------------------------------------------------------------------------------------------
function markSvg(size, { bg, check = WHITE, handColor = ORANGE, scale = 1 }) {
  const c = size / 2;
  const s = (size / 1024) * scale;
  const p = (vx, vy) => `${round(c + (vx - 512) * s)} ${round(c + (vy - 512) * s)}`;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">
  ${bg ? `<rect width="${size}" height="${size}" fill="${bg}"/>` : ''}
  <path d="M ${p(300, 540)} L ${p(450, 690)}" stroke="${check}" stroke-width="${round(92 * s)}" stroke-linecap="round" fill="none"/>
  <path d="M ${p(450, 690)} L ${p(735, 320)}" stroke="${handColor}" stroke-width="${round(92 * s)}" stroke-linecap="round" fill="none"/>
  ${bg ? `<circle cx="${p(450, 690).split(' ')[0]}" cy="${p(450, 690).split(' ')[1]}" r="${round(30 * s)}" fill="${bg}"/>` : ''}
</svg>`;
}
const icons = [
  ['assets/icon.png', markSvg(1024, { bg: CHARCOAL })],
  ['assets/android-icon-foreground.png', markSvg(1024, { scale: 0.62 })],
  ['assets/android-icon-monochrome.png', markSvg(1024, { scale: 0.62, check: WHITE, handColor: WHITE })],
  ['assets/favicon.png', markSvg(48, { bg: CHARCOAL })],
];
for (const [file, svg] of icons) writeFileSync(out(file), new Resvg(svg).render().asPng());
// The template's adaptive background is not used (solid colour in app.config.ts).

console.log('Brand assets rendered:', { viewBox, hand });
